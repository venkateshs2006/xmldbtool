    public JobLaunchResponse runJob(String jobId, String username) {
        Optional<JobLaunchRequest> opt = getJobConfig(jobId);
        if (opt.isEmpty()) {
            throw new NoSuchElementException("Job not found: " + jobId);
        }
        JobLaunchRequest req = opt.get();

        String approval = req.getApprovalStatus();
        if (!"APPROVED".equalsIgnoreCase(approval)) {
            throw new IllegalStateException("Job " + jobId + " cannot be executed because approval status is " + approval + ". It must be APPROVED first.");
        }

        if ("RUNNING".equalsIgnoreCase(req.getLastRunStatus())) {
            throw new IllegalStateException("Job " + jobId + " is already running.");
        }

        // Ensure default dbConfig if not specified
        DbConnectionConfig dbConfig = req.getDbConfig();
        if (dbConfig == null || dbConfig.getUrl() == null || dbConfig.getUrl().trim().isEmpty()) {
            dbConfig = new DbConnectionConfig();
            dbConfig.setUrl("jdbc:postgresql://localhost:5432/v5_batch_db");
            dbConfig.setUsername("postgres");
            dbConfig.setPassword("postgres");
            dbConfig.setEngine("POSTGRESQL");
            dbConfig.setSchema("public");
            req.setDbConfig(dbConfig);
        }

        String execId = "EXEC-" + System.currentTimeMillis() + "-" + (idSequence.incrementAndGet() % 1000);
        req.setJobExecutionId(execId);
        req.setExecutionId(execId);
        req.setStatus("RUNNING");
        req.setLastRunStatus("RUNNING");
        String nowStr = java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
        req.setLastRunAt(nowStr);
        req.setStartTime(nowStr);
        req.setCurrentPhase("STREAMING");
        req.setUpdatedAt(Timestamp.from(Instant.now()));
        executionToJobMap.put(execId, jobId);
        persistJobToDb(req);

        // Execute streaming + canonical normalization in virtual thread
        Thread.ofVirtual().name("BatchPipeline-" + execId).start(() -> {
            long startTimeMs = System.currentTimeMillis();
            JobTelemetryResponse telem = new JobTelemetryResponse();
            telem.setJobExecutionId(execId);
            telem.setExecutionId(execId);
            telem.setJobId(jobId);
            telem.setStatus("RUNNING");
            telem.setStreamingState("STREAMING");
            telem.setStartTimeMs(startTimeMs);
            telem.setStartTime(nowStr);
            telem.setCurrentAction("Streaming XML to DB");
            telem.setCurrentPhase("PHASE 1 - INGESTION");
            if (req.getTargetTables() != null) {
                telem.setTargetTables(new ArrayList<>(req.getTargetTables()));
            }
            telemetryStore.put(execId, telem);

            try {
                log.info("Starting batch pipeline execution {} for job {}", execId, jobId);

                List<FieldMapping> mappings = req.getMappings();
                if ((mappings == null || mappings.isEmpty()) && req.getIngestionJson() != null) {
                    mappings = schemaProvisioningService.parseMappings(req.getIngestionJson());
                }

                FileHistoryRecord fileRec = auditGovernanceService.registerOrResolveFile(
                        req.getDbConfig(),
                        req.getXmlFilePath(),
                        req.getVendorName(),
                        req.getVendorId(),
                        req.getIngestionJson(),
                        username != null ? username : req.getSubmittedBy()
                );

                schemaProvisioningService.provisionAllTables(req.getDbConfig(), mappings);

                // Audit: JOB_STARTED
                AuditLogRecord startAudit = new AuditLogRecord();
                startAudit.setFileId(fileRec.getFileId());
                startAudit.setJobExecutionId(execId);
                startAudit.setEventType("JOB_STARTED");
                startAudit.setEntityName("INGESTION_PIPELINE");
                startAudit.setActionDetails("Initiated StAX streaming batch ingestion for file " + fileRec.getXmlFilename());
                startAudit.setExecutionStatus("RUNNING");
                startAudit.setTriggeredBy(username != null ? username : req.getSubmittedBy());
                auditGovernanceService.logAudit(req.getDbConfig(), startAudit);

                if (dynamicBatchJobService != null) {
                    log.info("Executing Spring Batch 5 Job for execution {}...", execId);
                    org.springframework.batch.core.JobExecution batchExec =
                            dynamicBatchJobService.launchSpringBatchIngestion(req, fileRec, mappings, execId);

                    DynamicJdbcBatchWriter writer = dynamicBatchJobService.getActiveWriter(execId);
                    long totalWritten = writer != null ? writer.getTotalRowsWritten() : 0;
                    Map<String, Long> writeCounts = writer != null ? writer.getTableWriteCounts() : Collections.emptyMap();

                    telem.setTotalRecords(totalWritten);
                    telem.setRecordsRead(totalWritten);
                    telem.setRecordsWritten(totalWritten);
                    telem.setTotalWritten(totalWritten);
                    telem.setTotalRead(totalWritten);
                    telem.setTableCounts(new HashMap<>(writeCounts));
                    telem.setTableRowCounts(new HashMap<>(writeCounts));
                    telem.setTableWriteCounts(new HashMap<>(writeCounts));
                    telem.setTargetTables(new ArrayList<>(writeCounts.keySet()));
                    
                    long elapsedSec = Math.max(1, (System.currentTimeMillis() - startTimeMs) / 1000);
                    double throughput = (double) totalWritten / elapsedSec;
                    telem.setThroughput(throughput);
                    telem.setRecordsPerSecond(throughput);
                    telem.setWriteThroughput(throughput);
                    telem.setReadThroughput(throughput);
                    telem.setDuration(elapsedSec + "s");

                    // Ensure canonical tables are synchronized and enterprise lineage is complete
                    telem.setStreamingState("NORMALIZING");
                    telem.setCurrentAction("Normalizing canonical entities");
                    long canonicalCount = canonicalNormalizationService.normalizeAndUpsertCanonical(
                            req.getDbConfig(), fileRec, mappings, execId
                    );

                    String endStr = java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
                    req.setStatus("COMPLETED");
                    req.setLastRunStatus("COMPLETED");
                    req.setEndTime(endStr);
                    req.setDuration(elapsedSec + "s");
                    req.setTotalWritten(totalWritten);
                    req.setTotalRead(totalWritten);
                    req.setTableWriteCounts(new HashMap<>(writeCounts));
                    req.setTargetTables(new ArrayList<>(writeCounts.keySet()));

                    telem.setStatus("COMPLETED");
                    telem.setStreamingState("COMPLETED");
                    telem.setCurrentAction("Completed successfully.");
                    telem.setEndTime(endStr);
                    telem.setCompletedTables(writeCounts.size());
                    telem.setPendingTables(0);
                    log.info("Spring Batch execution {} completed. Total written: {}, Canonical rows: {}",
                            execId, totalWritten, canonicalCount);
                } else {
                    telem = xmlStreamingParserService.streamAndIngest(
                            req.getDbConfig(), fileRec, mappings, execId, 0
                    );
                    telemetryStore.put(execId, telem);
                    if (!"STOPPED".equalsIgnoreCase(telem.getStatus())) {
                        canonicalNormalizationService.normalizeAndUpsertCanonical(
                                req.getDbConfig(), fileRec, mappings, execId
                        );
                        req.setStatus("COMPLETED");
                        req.setLastRunStatus("COMPLETED");
                        telem.setStatus("COMPLETED");
                    } else {
                        req.setStatus("STOPPED");
                        req.setLastRunStatus("STOPPED");
                    }
                }
            } catch (Exception ex) {
                log.error("Batch pipeline execution {} failed: {}", execId, ex.getMessage(), ex);
                String endStr = java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
                req.setStatus("FAILED");
                req.setLastRunStatus("FAILED");
                req.setEndTime(endStr);
                telem.setStatus("FAILED");
                telem.setStreamingState("FAILED");
                telem.setErrorMessage(ex.getMessage());
                telem.setMessage(ex.getMessage());
                telem.setEndTime(endStr);

                MigrationErrorRecord fatalRecord = new MigrationErrorRecord(
                        null,
                        "batchJob",
                        "JOB_FATAL",
                        "{\"jobExecutionId\": \"" + execId + "\", \"error\": \"" + (ex.getMessage() != null ? ex.getMessage().replace("\"", "\\\"") : "Unknown") + "\"}",
                        ex.getMessage(),
                        endStr
                );
                List<MigrationErrorRecord> errList = new ArrayList<>();
                errList.add(fatalRecord);
                if (dynamicBatchJobService != null) {
                    DatabaseErrorSkipListener listener = dynamicBatchJobService.getActiveSkipListener(execId);
                    if (listener != null) {
                        errList.addAll(listener.getRecentErrors());
                    }
                }
                telem.setRecentErrors(errList);

                ErrorLogRecord err = new ErrorLogRecord();
                err.setJobExecutionId(execId);
                err.setErrorSeverity("FATAL");
                err.setErrorType("PIPELINE_EXECUTION_FAILURE");
                err.setErrorMessage(ex.getMessage());
                auditGovernanceService.logError(req.getDbConfig(), err);
            } finally {
                req.setUpdatedAt(Timestamp.from(Instant.now()));
                persistJobToDb(req);
            }
        });

        return new JobLaunchResponse(true, jobId, execId, "RUNNING", "Job execution launched successfully.");
    }

    public boolean stopJob(String execId) {
        if (execId == null) return false;
        xmlStreamingParserService.requestStop(execId);
        String jobId = executionToJobMap.get(execId);
        if (jobId != null) {
            Optional<JobLaunchRequest> opt = getJobConfig(jobId);
            opt.ifPresent(r -> r.setStatus("STOPPED"));
        }
        return true;
    }

    public JobLaunchResponse resumeJob(String execId) {
        if (execId == null) {
            throw new IllegalArgumentException("Execution ID is required.");
        }
        String jobId = executionToJobMap.get(execId);
        if (jobId == null) {
            throw new NoSuchElementException("No job associated with execution " + execId);
        }
        JobLaunchRequest req = jobStore.get(jobId);
        if (req == null) {
            throw new NoSuchElementException("Job not found: " + jobId);
        }

        JobCheckpointRecord cp = auditGovernanceService.getCheckpoint(req.getDbConfig(), execId);
        long startFrom = cp != null ? cp.getRecordsStreamed() : 0;

        req.setStatus("RUNNING");
        req.setUpdatedAt(Timestamp.from(Instant.now()));

        Thread.ofVirtual().name("BatchPipeline-Resume-" + execId).start(() -> {
            try {
                List<FieldMapping> mappings = req.getMappings();
                if ((mappings == null || mappings.isEmpty()) && req.getIngestionJson() != null) {
                    mappings = schemaProvisioningService.parseMappings(req.getIngestionJson());
                }

                FileHistoryRecord fileRec = auditGovernanceService.registerOrResolveFile(
                        req.getDbConfig(), req.getXmlFilePath(), req.getVendorName(), req.getVendorId(), req.getIngestionJson(), req.getSubmittedBy()
                );

                JobTelemetryResponse telem = xmlStreamingParserService.streamAndIngest(
                        req.getDbConfig(), fileRec, mappings, execId, startFrom
                );

                if (!"STOPPED".equalsIgnoreCase(telem.getStatus())) {
                    canonicalNormalizationService.normalizeAndUpsertCanonical(req.getDbConfig(), fileRec, mappings, execId);
                    req.setStatus("COMPLETED");
                    telem.setStatus("COMPLETED");
                } else {
                    req.setStatus("STOPPED");
                }
            } catch (Exception ex) {
                log.error("Resume execution {} failed: {}", execId, ex.getMessage(), ex);
                req.setStatus("FAILED");
            }
        });

        return new JobLaunchResponse(true, jobId, execId, "RUNNING", "Resumed execution from index " + startFrom);
    }

