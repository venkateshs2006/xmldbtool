package com.bnpp.service;

import com.bnpp.config.TablePrefixConfig;
import com.bnpp.model.*;
import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;
import java.util.*;

@Service
public class SchemaProvisioningService {

    private static final Logger log = LoggerFactory.getLogger(SchemaProvisioningService.class);

    private static final Set<String> RESERVED_KEYWORDS = Set.of(
            "year", "month", "day", "user", "order", "group", "table", "select", "from",
            "where", "values", "value", "key", "offset", "limit", "date", "time", "timestamp",
            "primary", "foreign", "check", "column", "constraint", "index", "references"
    );

    private final DynamicDataSourceService dataSourceService;
    private final AuditGovernanceService auditGovernanceService;
    private final ObjectMapper objectMapper;
    private final TablePrefixConfig tablePrefixConfig;

    @Autowired
    public SchemaProvisioningService(DynamicDataSourceService dataSourceService,
                                     AuditGovernanceService auditGovernanceService,
                                     ObjectMapper objectMapper,
                                     @Autowired(required = false) TablePrefixConfig tablePrefixConfig) {
        this.dataSourceService = dataSourceService;
        this.auditGovernanceService = auditGovernanceService;
        this.objectMapper = objectMapper;
        this.tablePrefixConfig = tablePrefixConfig != null ? tablePrefixConfig : new TablePrefixConfig();
    }

    public TablePrefixConfig getTablePrefixConfig() {
        return tablePrefixConfig;
    }

    public String safeColumnName(String col) {
        if (col == null) return null;
        String lower = col.trim().toLowerCase();
        if (RESERVED_KEYWORDS.contains(lower)) {
            return "\"" + lower + "\"";
        }
        return lower;
    }

    public List<FieldMapping> parseMappings(String ingestionJson) {
        if (ingestionJson == null || ingestionJson.trim().isEmpty()) {
            return Collections.emptyList();
        }
        try {
            JsonNode rootNode = objectMapper.readTree(ingestionJson);
            if (rootNode.isArray()) {
                return objectMapper.readValue(ingestionJson, new TypeReference<List<FieldMapping>>() {});
            } else if (rootNode.has("mappings") && rootNode.get("mappings").isArray()) {
                return objectMapper.readValue(rootNode.get("mappings").toString(), new TypeReference<List<FieldMapping>>() {});
            } else {
                return Collections.emptyList();
            }
        } catch (Exception ex) {
            log.error("Failed to parse ingestion.json: {}", ex.getMessage());
            throw new IllegalArgumentException("Invalid ingestion.json mapping: " + ex.getMessage(), ex);
        }
    }

    public void provisionAllTables(DbConnectionConfig config, List<FieldMapping> mappings) {
        // 1. Layer 1: Governance, Audit & Error tables
        auditGovernanceService.ensureGovernanceTablesExist(config);

        DataSource ds = dataSourceService.getOrCreateDataSource(config);

        // 2. Layer 2: Universal Staging table
        provisionStagingTable(ds);

        // 3. Layer 3 & 4: Golden Source and Canonical tables
        Map<String, List<FieldMapping>> tableMap = groupMappingsByTable(mappings);

        for (Map.Entry<String, List<FieldMapping>> entry : tableMap.entrySet()) {
            String rawTable = entry.getKey();
            String entityName = tablePrefixConfig.cleanEntityName(rawTable);
            List<FieldMapping> cols = entry.getValue();

            provisionGoldenSourceTable(ds, entityName, cols);
            provisionCanonicalTable(ds, entityName, cols);
        }

        log.info("Successfully provisioned all database layers for {} entities with prefixes (GS: '{}', Canonical: '{}').",
                tableMap.size(), tablePrefixConfig.getGoldenSource(), tablePrefixConfig.getCanonical());
    }

    private void provisionStagingTable(DataSource ds) {
        String sql = """
            CREATE TABLE IF NOT EXISTS staging_xml_records (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                job_execution_id VARCHAR(64),
                file_id VARCHAR(64),
                bnpp_id VARCHAR(64),
                tag_name VARCHAR(128),
                version_number INT DEFAULT 1,
                entity_type VARCHAR(128),
                record_identifier VARCHAR(128),
                record_action VARCHAR(64),
                record_date VARCHAR(64),
                xml_file_version INT DEFAULT 1,
                raw_payload TEXT,
                payload_hash VARCHAR(128),
                status VARCHAR(64) DEFAULT 'STAGED',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                created_by VARCHAR(128),
                updated_by VARCHAR(128)
            )
        """;
        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute(sql);
            log.info("Layer 2 Universal Staging table verified/created: staging_xml_records");
        } catch (Exception ex) {
            String msg = ex.getMessage() != null ? ex.getMessage().toLowerCase() : "";
            if (msg.contains("already exists") || msg.contains("duplicate") || msg.contains("42p07") || msg.contains("42s01") || msg.contains("table exists")) {
                log.info("Staging table 'staging_xml_records' already exists. Ignoring table creation and proceeding.");
                return;
            }
            log.warn("Non-fatal warning executing DDL for staging_xml_records: {}", ex.getMessage());
        }
    }

    private void provisionGoldenSourceTable(DataSource ds, String entityName, List<FieldMapping> mappings) {
        String tableName = tablePrefixConfig.getGoldenSourceTableName(entityName);
        StringBuilder sb = new StringBuilder();
        sb.append("CREATE TABLE IF NOT EXISTS ").append(tableName).append(" (\n");
        sb.append("    bnpp_id VARCHAR(64) PRIMARY KEY,\n");

        Set<String> addedCols = new HashSet<>();
        addedCols.add("bnpp_id");

        for (FieldMapping m : mappings) {
            String col = m.getTargetColumn().toLowerCase();
            if (addedCols.add(col)) {
                String dType = determineSqlType(m);
                sb.append("    ").append(safeColumnName(col)).append(" ").append(dType).append(",\n");
            }
        }

        // Layer 3 System columns
        sb.append("    file_id VARCHAR(64),\n");
        sb.append("    file_version INT DEFAULT 1,\n");
        sb.append("    vendor_id VARCHAR(64),\n");
        sb.append("    job_execution_id VARCHAR(64),\n");
        sb.append("    staging_bnpp_id VARCHAR(64),\n");
        sb.append("    raw_payload TEXT,\n");
        sb.append("    tag_name VARCHAR(128),\n");
        sb.append("    tag_type VARCHAR(64),\n");
        sb.append("    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,\n");
        sb.append("    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,\n");
        sb.append("    created_by VARCHAR(128),\n");
        sb.append("    updated_by VARCHAR(128)\n");
        sb.append(")");

        executeDdl(ds, sb.toString(), tableName);
    }

    private void provisionCanonicalTable(DataSource ds, String entityName, List<FieldMapping> mappings) {
        String tableName = tablePrefixConfig.getCanonicalTableName(entityName);
        StringBuilder sb = new StringBuilder();
        sb.append("CREATE TABLE IF NOT EXISTS ").append(tableName).append(" (\n");

        // Find primary key column from mappings
        FieldMapping pkMapping = mappings.stream()
                .filter(m -> "PK".equalsIgnoreCase(m.getConstraintType()))
                .findFirst()
                .orElse(null);

        String pkCol = pkMapping != null ? pkMapping.getTargetColumn().toLowerCase() : "id";
        String pkType = pkMapping != null ? determineSqlType(pkMapping) : "VARCHAR(128)";

        sb.append("    ").append(safeColumnName(pkCol)).append(" ").append(pkType).append(" PRIMARY KEY,\n");

        Set<String> addedCols = new HashSet<>();
        addedCols.add(pkCol);

        for (FieldMapping m : mappings) {
            String col = m.getTargetColumn().toLowerCase();
            if (addedCols.add(col)) {
                String dType = determineSqlType(m);
                sb.append("    ").append(safeColumnName(col)).append(" ").append(dType).append(",\n");
            }
        }

        // Layer 4 Lineage system columns
        sb.append("    starting_bnpp_id VARCHAR(64),\n");
        sb.append("    current_bnpp_id VARCHAR(64),\n");
        sb.append("    file_id VARCHAR(64),\n");
        sb.append("    file_version_number INT DEFAULT 1,\n");
        sb.append("    vendor_id VARCHAR(64),\n");
        sb.append("    historical_bnpp_ids TEXT,\n");
        sb.append("    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,\n");
        sb.append("    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,\n");
        sb.append("    created_by VARCHAR(128),\n");
        sb.append("    updated_by VARCHAR(128)\n");
        sb.append(")");

        executeDdl(ds, sb.toString(), tableName);
    }

    private void executeDdl(DataSource ds, String sql, String tableName) {
        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute(sql);
            log.info("Executed DDL for table '{}'", tableName);
        } catch (Exception ex) {
            String msg = ex.getMessage() != null ? ex.getMessage().toLowerCase() : "";
            if (msg.contains("already exists") || msg.contains("duplicate") || msg.contains("42p07") || msg.contains("42s01") || msg.contains("table exists")) {
                log.info("Table '{}' already exists. Ignoring table creation and proceeding with subsequent steps.", tableName);
                return;
            }
            log.warn("Non-fatal warning executing DDL for table '{}': {}", tableName, ex.getMessage());
        }
    }

    public List<String> createForeignKeyConstraints(DbConnectionConfig config, List<FieldMapping> mappings) {
        if (mappings == null || mappings.isEmpty()) {
            return Collections.emptyList();
        }
        DataSource ds = dataSourceService.getOrCreateDataSource(config);
        return createForeignKeyConstraints(ds, mappings);
    }

    public List<String> createForeignKeyConstraints(DataSource ds, List<FieldMapping> mappings) {
        if (mappings == null || mappings.isEmpty()) {
            return Collections.emptyList();
        }

        List<String> createdConstraints = new ArrayList<>();
        Set<String> processedKeys = new HashSet<>();

        List<FieldMapping> fkMappings = mappings.stream()
                .filter(m -> "FK".equalsIgnoreCase(m.getConstraintType()))
                .toList();

        if (fkMappings.isEmpty()) {
            log.info("No foreign key constraints defined in mappings.");
            return createdConstraints;
        }

        try (Connection conn = ds.getConnection()) {
            boolean originalAutoCommit = true;
            try {
                originalAutoCommit = conn.getAutoCommit();
                conn.setAutoCommit(true);
            } catch (Exception ignored) {}

            try {
                for (FieldMapping m : fkMappings) {
                    if (m.getTargetTable() == null || m.getTargetColumn() == null) continue;

                    String sourceEntity = tablePrefixConfig.cleanEntityName(m.getTargetTable());
                    String sourceTable = tablePrefixConfig.getCanonicalTableName(sourceEntity);
                    String sourceCol = m.getTargetColumn().toLowerCase().trim();

                    // Resolve referenced table and column from "references" field (e.g. "descriptionlist2.id")
                    String refEntity = null;
                    String refCol = null;

                    String refs = m.getReferences();
                    if (refs != null && !refs.trim().isEmpty()) {
                        String cleanRefs = refs.trim();
                        if (cleanRefs.contains(".")) {
                            String[] parts = cleanRefs.split("\\.", 2);
                            refEntity = parts[0].trim();
                            refCol = parts[1].trim();
                        } else if (cleanRefs.contains("(")) {
                            refEntity = cleanRefs.substring(0, cleanRefs.indexOf('(')).trim();
                            refCol = cleanRefs.substring(cleanRefs.indexOf('(') + 1, cleanRefs.indexOf(')')).trim();
                        } else {
                            refEntity = cleanRefs;
                            refCol = "id";
                        }
                    }

                    if (refEntity == null || refEntity.trim().isEmpty()) {
                        refEntity = m.getForeignKeyTable();
                    }
                    if (refCol == null || refCol.trim().isEmpty()) {
                        refCol = m.getForeignKeyColumn();
                    }

                    // Fallback heuristic: If referenced entity is still unknown, derive from source column name
                    // e.g. "descriptionlist2_id" -> entity "descriptionlist2", col "id"
                    // "countrylist_id" -> entity "countrylist", col "id"
                    // "descriptionlist1_id" -> entity "descriptionlist1", col "id"
                    if ((refEntity == null || refEntity.trim().isEmpty()) && sourceCol.endsWith("_id") && sourceCol.length() > 3) {
                        refEntity = sourceCol.substring(0, sourceCol.length() - 3);
                        if (refCol == null || refCol.trim().isEmpty()) {
                            refCol = "id";
                        }
                    }

                    if (refCol == null || refCol.trim().isEmpty()) {
                        refCol = "id";
                    }

                    if (refEntity == null || refEntity.trim().isEmpty()) {
                        log.warn("Skipping FK constraint on {}.{}: referenced table is unknown", sourceTable, sourceCol);
                        continue;
                    }

                    refEntity = tablePrefixConfig.cleanEntityName(refEntity);
                    String refTable = tablePrefixConfig.getCanonicalTableName(refEntity);
                    refCol = refCol.toLowerCase().trim();

                    String dedupKey = sourceTable.toLowerCase() + "." + sourceCol.toLowerCase();
                    if (!processedKeys.add(dedupKey)) {
                        continue;
                    }

                    String constraintName = buildConstraintName(sourceTable, sourceCol);

                    if (foreignKeyConstraintExists(conn, sourceTable, sourceCol, constraintName)) {
                        log.info("Foreign key constraint {} already exists on {}({}). Skipping.", constraintName, sourceTable, sourceCol);
                        createdConstraints.add(constraintName);
                        continue;
                    }

                    String sql = String.format("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s)",
                            sourceTable, constraintName, safeColumnName(sourceCol), refTable, safeColumnName(refCol));

                    try (Statement stmt = conn.createStatement()) {
                        stmt.execute(sql);
                        log.info("Successfully created foreign key constraint: {} ({}.{} -> {}.{})",
                                constraintName, sourceTable, sourceCol, refTable, refCol);
                        createdConstraints.add(constraintName);
                    } catch (Exception ex) {
                        String msg = ex.getMessage() != null ? ex.getMessage().toLowerCase() : "";
                        if (msg.contains("already exists") || msg.contains("duplicate") || msg.contains("ora-02275")) {
                            log.info("Foreign key constraint {} already exists on {}({})", constraintName, sourceTable, sourceCol);
                            createdConstraints.add(constraintName);
                        } else {
                            log.warn("Could not create foreign key constraint {} ({}.{} -> {}.{}): {}",
                                    constraintName, sourceTable, sourceCol, refTable, refCol, ex.getMessage());
                        }
                    }
                }
            } finally {
                try {
                    conn.setAutoCommit(originalAutoCommit);
                } catch (Exception ignored) {}
            }
        } catch (Exception ex) {
            log.error("Error creating foreign key constraints: {}", ex.getMessage(), ex);
            throw new RuntimeException("Error creating foreign key constraints: " + ex.getMessage(), ex);
        }

        log.info("Finished applying foreign key constraints: {} constraints created/verified.", createdConstraints.size());
        return createdConstraints;
    }

    public void dropForeignKeyConstraints(DbConnectionConfig config, List<FieldMapping> mappings) {
        if (mappings == null || mappings.isEmpty()) return;
        DataSource ds = dataSourceService.getOrCreateDataSource(config);
        dropForeignKeyConstraints(ds, mappings);
    }

    public void dropForeignKeyConstraints(DataSource ds, List<FieldMapping> mappings) {
        if (mappings == null || mappings.isEmpty()) return;
        List<FieldMapping> fkMappings = mappings.stream()
                .filter(m -> "FK".equalsIgnoreCase(m.getConstraintType()))
                .toList();
        if (fkMappings.isEmpty()) return;

        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement()) {
            Set<String> dropped = new HashSet<>();
            for (FieldMapping m : fkMappings) {
                if (m.getTargetTable() == null || m.getTargetColumn() == null) continue;
                String sourceEntity = tablePrefixConfig.cleanEntityName(m.getTargetTable());
                String sourceTable = tablePrefixConfig.getCanonicalTableName(sourceEntity);
                String sourceCol = m.getTargetColumn().toLowerCase().trim();
                String constraintName = buildConstraintName(sourceTable, sourceCol);
                if (!dropped.add(constraintName)) continue;

                try {
                    stmt.execute("ALTER TABLE " + sourceTable + " DROP CONSTRAINT " + constraintName);
                    log.info("Dropped existing FK constraint {} on {}", constraintName, sourceTable);
                } catch (Exception ignored) {
                    // Constraint did not exist
                }
            }
        } catch (Exception ex) {
            log.debug("Error while dropping FK constraints: {}", ex.getMessage());
        }
    }

    private String buildConstraintName(String sourceTable, String sourceCol) {
        String base = ("fk_" + sourceTable + "_" + sourceCol).toLowerCase();
        if (base.length() > 30) {
            return "fk_" + Math.abs((sourceTable + "_" + sourceCol).hashCode());
        }
        return base;
    }

    private boolean foreignKeyConstraintExists(Connection conn, String tableName, String colName, String constraintName) {
        try {
            java.sql.DatabaseMetaData meta = conn.getMetaData();
            for (String t : List.of(tableName, tableName.toUpperCase(), tableName.toLowerCase())) {
                try (java.sql.ResultSet rs = meta.getImportedKeys(null, null, t)) {
                    while (rs.next()) {
                        String fkCol = rs.getString("FKCOLUMN_NAME");
                        String fkName = rs.getString("FK_NAME");
                        if (colName.equalsIgnoreCase(fkCol) || (constraintName != null && constraintName.equalsIgnoreCase(fkName))) {
                            return true;
                        }
                    }
                } catch (Exception ignored) {}
            }
        } catch (Exception ignored) {}
        return false;
    }

    public TablePreviewData generatePreviewTables(List<FieldMapping> mappings) {
        List<TableMetadata> tables = new ArrayList<>();
        List<TableRelationship> rels = new ArrayList<>();
        StringBuilder combinedDdl = new StringBuilder();

        // 1. Governance tables
        TableMetadata fileHist = new TableMetadata("file_history", "GOVERNANCE", "file_history");
        fileHist.setPrimaryKeyColumn("file_id");
        tables.add(fileHist);

        TableMetadata auditLogs = new TableMetadata("audit_logs", "AUDIT", "audit_logs");
        auditLogs.setPrimaryKeyColumn("audit_id");
        tables.add(auditLogs);

        TableMetadata errLogs = new TableMetadata("error_logs", "ERROR", "error_logs");
        errLogs.setPrimaryKeyColumn("error_id");
        tables.add(errLogs);

        TableMetadata checkpoints = new TableMetadata("job_checkpoints", "GOVERNANCE", "job_checkpoints");
        checkpoints.setPrimaryKeyColumn("job_execution_id");
        tables.add(checkpoints);

        // 2. Staging table
        TableMetadata staging = new TableMetadata("staging_xml_records", "STAGING", "staging");
        staging.setPrimaryKeyColumn("id");
        tables.add(staging);

        // 3. Mapped Entities
        Map<String, List<FieldMapping>> tableMap = groupMappingsByTable(mappings);
        for (Map.Entry<String, List<FieldMapping>> entry : tableMap.entrySet()) {
            String rawTable = entry.getKey();
            String entityName = tablePrefixConfig.cleanEntityName(rawTable);
            List<FieldMapping> cols = entry.getValue();

            // Golden Source
            String gsTableName = tablePrefixConfig.getGoldenSourceTableName(entityName);
            TableMetadata gsTable = new TableMetadata(gsTableName, "GOLDEN_SOURCE", entityName);
            gsTable.setPrimaryKeyColumn("bnpp_id");
            for (FieldMapping m : cols) {
                gsTable.getColumns().add(new ColumnMetadata(m.getTargetColumn().toLowerCase(), determineSqlType(m), "PK".equalsIgnoreCase(m.getConstraintType())));
            }
            tables.add(gsTable);

            // Canonical
            String canTableName = tablePrefixConfig.getCanonicalTableName(entityName);
            TableMetadata canTable = new TableMetadata(canTableName, "CANONICAL", entityName);
            FieldMapping pkMapping = cols.stream().filter(m -> "PK".equalsIgnoreCase(m.getConstraintType())).findFirst().orElse(null);
            canTable.setPrimaryKeyColumn(pkMapping != null ? pkMapping.getTargetColumn().toLowerCase() : "id");
            for (FieldMapping m : cols) {
                boolean isPk = "PK".equalsIgnoreCase(m.getConstraintType());
                boolean isFk = "FK".equalsIgnoreCase(m.getConstraintType());
                canTable.getColumns().add(new ColumnMetadata(
                        m.getTargetColumn().toLowerCase(),
                        determineSqlType(m),
                        isPk,
                        isFk,
                        m.getForeignKeyTable(),
                        m.getForeignKeyColumn()
                ));
                if (isFk && m.getForeignKeyTable() != null) {
                    String fkTable = tablePrefixConfig.getCanonicalTableName(m.getForeignKeyTable());
                    rels.add(new TableRelationship(canTableName, m.getTargetColumn().toLowerCase(), fkTable, m.getForeignKeyColumn() != null ? m.getForeignKeyColumn().toLowerCase() : "id"));
                }
            }
            tables.add(canTable);
        }

        return new TablePreviewData(tables, rels, combinedDdl.toString(), tablePrefixConfig.getGoldenSource(), tablePrefixConfig.getCanonical());
    }

    private Map<String, List<FieldMapping>> groupMappingsByTable(List<FieldMapping> mappings) {
        Map<String, List<FieldMapping>> map = new LinkedHashMap<>();
        if (mappings == null) return map;
        for (FieldMapping m : mappings) {
            if (m.getTargetTable() == null || m.getTargetTable().trim().isEmpty()) continue;
            map.computeIfAbsent(m.getTargetTable().trim(), k -> new ArrayList<>()).add(m);
        }
        return map;
    }

    public String determineSqlType(FieldMapping m) {
        String transform = m.getTransform() != null ? m.getTransform().toUpperCase() : "NONE";
        return switch (transform) {
            case "TO_INT" -> "INT";
            case "TO_LONG" -> "BIGINT";
            case "TO_BOOLEAN" -> "BOOLEAN";
            case "TO_DATE" -> "TIMESTAMP";
            case "TO_DECIMAL", "TO_DOUBLE", "TO_NUMERIC" -> "NUMERIC(18, 4)";
            default -> "VARCHAR(256)";
        };
    }
}
