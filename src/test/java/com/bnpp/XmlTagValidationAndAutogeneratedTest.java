package com.bnpp;

import com.bnpp.batch.DynamicXmlItemProcessor;
import com.bnpp.model.FieldMapping;
import com.bnpp.service.XmlSchemaDiscoveryService;
import org.junit.jupiter.api.Test;

import java.io.File;
import java.util.List;
import java.util.Map;
import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.*;

public class XmlTagValidationAndAutogeneratedTest {

    @Test
    void testAutogeneratedPatternAndHelper() {
        assertTrue(DynamicXmlItemProcessor.isAutogenerated("autogenerated"));
        assertTrue(DynamicXmlItemProcessor.isAutogenerated("Auto-Generated"));
        assertTrue(DynamicXmlItemProcessor.isAutogenerated("AUTO_GENERATED"));
        assertFalse(DynamicXmlItemProcessor.isAutogenerated("person/id"));
        assertFalse(DynamicXmlItemProcessor.isAutogenerated(null));

        String val1 = DynamicXmlItemProcessor.generateAutogeneratedValue();
        String val2 = DynamicXmlItemProcessor.generateAutogeneratedValue();

        assertNotNull(val1);
        assertNotNull(val2);
        assertNotEquals(val1, val2);

        // Format: R_<14 digits yyyyMMddHHmmss + 6 digits microseconds>_<7 digits random>
        // Total 20 digits after R_ and 7 digits after underscore
        Pattern pattern = Pattern.compile("^R_\\d{20}_\\d{7}$");
        assertTrue(pattern.matcher(val1).matches(), "Value " + val1 + " should match R_<datetime_with_microsec>_<7digit_random>");
        assertTrue(pattern.matcher(val2).matches(), "Value " + val2 + " should match R_<datetime_with_microsec>_<7digit_random>");
    }

    @Test
    void testXmlTagValidationWithAutogeneratedIgnored() {
        XmlSchemaDiscoveryService service = new XmlSchemaDiscoveryService();

        File sampleFile = new File("sample-data", "sample.xml");
        if (!sampleFile.exists()) {
            sampleFile = new File("uploads", "tester.xml");
        }
        assertTrue(sampleFile.exists(), "Sample XML must exist for test");

        FieldMapping m1 = new FieldMapping();
        m1.setXmlField("autogenerated");
        m1.setTargetTable("tester");
        m1.setTargetColumn("generated_col");

        FieldMapping m2 = new FieldMapping();
        m2.setXmlField("organization/departments/department/@code");
        m2.setTargetTable("department");
        m2.setTargetColumn("code");

        FieldMapping m3 = new FieldMapping();
        m3.setXmlField("completely_nonexistent_tag_xyz");
        m3.setTargetTable("bad");
        m3.setTargetColumn("bad_col");

        Map<String, Object> resp = service.validateXmlTags(sampleFile.getAbsolutePath(), List.of(m1, m2, m3));
        assertTrue((Boolean) resp.get("success"));
        assertFalse((Boolean) resp.get("matched"));

        @SuppressWarnings("unchecked")
        List<String> mismatches = (List<String>) resp.get("mismatches");
        assertNotNull(mismatches);
        assertFalse(mismatches.isEmpty());

        // Autogenerated column should be ignored (not present in mismatches)
        for (String m : mismatches) {
            assertFalse(m.contains("generated_col"));
            assertFalse(m.contains("autogenerated"));
        }

        // Nonexistent tag must be reported
        boolean foundBadTag = mismatches.stream().anyMatch(m -> m.contains("completely_nonexistent_tag_xyz"));
        assertTrue(foundBadTag, "Mismatch list should contain the missing XML tag");
    }

    @Test
    void testResolvePathReturnsAbsolutePath() {
        XmlSchemaDiscoveryService service = new XmlSchemaDiscoveryService();
        File res = service.resolvePath("tester.xml", null);
        assertNotNull(res);
        assertTrue(res.isAbsolute());
        assertTrue(res.exists());
    }
}
